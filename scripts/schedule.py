#!/usr/bin/env python3
"""Builds shared/src/commonMain/kotlin/dev/hamper/tabula/data/Schedule.kt: every lecture of every parallel with its date and topic.

Input: a folder with the course plans BI-LA1.yaml and BI-DML.yaml (kept outside this repository), which follow the
harmonogram on courses.fit.cvut.cz (the file says which commit of the course page it was checked against). The lecture
table there says, per teaching week, which lecture each parallel has; a holiday is an empty cell. The weekday and time of
each parallel come from the faculty timetable (15. 11. 2026). Nothing about a student is in here: the app asks which
parallel you attend. SCHEDULE_PLANS (required, or the folder as the only argument) is the path to that folder.

    SCHEDULE_PLANS=<plans folder> uv run --with pyyaml python3 scripts/schedule.py
"""

import os
import re
import sys
from datetime import date, timedelta
from pathlib import Path

import yaml

SEMESTER_START = date(2026, 9, 21)  # Monday of teaching week 1 of B261
OUT = Path(__file__).resolve().parent.parent / "shared/src/commonMain/kotlin/dev/hamper/tabula/data/Schedule.kt"

# parallel -> (teacher, weekday 0 = Monday, start time); from the timetable, the same for every week
PARALLELS = {
    "BI-LA1": {"1": ("Kleprlík", 1, "16:15"), "2": ("Klouda", 2, "09:15"), "3": ("Krásenský", 4, "09:15")},
    "BI-DML": {"1": ("Dombek", 0, "14:30"), "2": ("Spěvák", 2, "11:00"), "3": ("Legerský", 3, "14:30")},
}


# LA1: where each lecturer got in the slides, per teaching week ("Kam jsme na přednášce dle prezentací došli" on the
# course page, GitLab BI-LA1/bi-la1 commit c8ecfbaf, read 15. 11. 2026). p3s13 = presentation 3, slide 13. None = no lecture.
REACHED = {
    "1": ["p1s13", "p1s33", "p2s10", "p2s24", "p2s46", "p3s08", "p4s00", "p4s25", None],
    "2": ["p1s14", "p1s29", "p2s00", "p2s25", "p2s46", None, "p3s13", "p4s05"],
    "3": ["p1s13", "p1s31", "p2s00", "p2s24", "p2s41", "p3s00", "p3s17", "p4s05"],
}


def reached_codes(parallel, week):
    """Slide sets a past LA1 lecture went through: from where the previous one stopped to where this one did."""
    marks = REACHED.get(parallel, [])
    if week > len(marks) or marks[week - 1] is None:
        return None
    pa, sa = map(int, re.match(r"p(\d+)s(\d+)", marks[week - 1]).groups())
    prev = next((m for m in reversed(marks[: week - 1]) if m), "p1s00")
    pb, sb = map(int, re.match(r"p(\d+)s(\d+)", prev).groups())
    sets = [p for p in range(pb, pa + 1) if not (p == pb and p < pa and sb == 0) and not (p == pa and sa == 0 and pa > pb)]
    return ["S%d" % p for p in sets], marks[week - 1]


def cell(row, parallel):
    """The lecture of one parallel in one week: 'P5 (MZ1)' or None."""
    if isinstance(row, dict):
        return row.get(parallel, row.get("all"))
    return row


def codes(course, label, topic, plan):
    """Topic codes a lecture covers. DML names them in the cell (MI2, MZ1); LA1 by slide sets (slajdy 3 -> S3)."""
    if course == "BI-DML":
        return [c.strip() for c in (topic or "").split(",") if c.strip()]
    title = (plan.get("topics", {}).get(label) or {}).get("title", "")
    m = re.search(r"slajdy ([\d a]+)\)", title)
    return ["S" + n for n in re.findall(r"\d+", m.group(1))] if m else []


def main(plans: Path):
    out = [
        "package dev.hamper.tabula.data",
        "",
        "import dev.hamper.tabula.compat.time.DayOfWeek",
        "import dev.hamper.tabula.compat.time.LocalDate",
        "import dev.hamper.tabula.compat.time.LocalTime",
        "import dev.hamper.tabula.compat.time.*",
        "",
        "/*",
        " * Generated by scripts/schedule.py from the course plans (BI-LA1.yaml, BI-DML.yaml, which follow the harmonogram",
        " * on courses.fit.cvut.cz) and the faculty timetable. Do not edit by hand: change the plan and run the script.",
        " */",
        "",
    ]
    for course in ("BI-LA1", "BI-DML"):
        plan = yaml.safe_load((plans / f"{course}.yaml").read_text())
        name = course.replace("BI-", "").title().replace("La1", "La1").replace("Dml", "Dml")
        out.append(f"/** {plan['name']}: plan checked {plan['checked']} against the course page (commit {plan['commit']}). */")
        out.append(f"val {name}Schedule = CourseSchedule(")
        out.append(f"    checked = LocalDate.parse(\"{plan['checked']}\"),")
        out.append("    parallels = listOf(")
        for p, (teacher, wd, t) in PARALLELS[course].items():
            dow = ["MONDAY", "TUESDAY", "WEDNESDAY", "THURSDAY", "FRIDAY"][wd]
            out.append(f"        Parallel(\"{p}\", \"{teacher}\", DayOfWeek.{dow}, LocalTime.parse(\"{t}\")),")
        out.append("    ),")
        out.append("    lectures = mapOf(")
        for p, (teacher, wd, t) in PARALLELS[course].items():
            out.append(f"        \"{p}\" to listOf(")
            for week, row in sorted(plan["lectures"].items()):
                c = cell(row, p)
                if not c:
                    continue
                m = re.match(r"(P\d+)(?:\s*\((.*)\))?$", c.strip())
                label, topic = m.group(1), m.group(2)
                d = SEMESTER_START + timedelta(days=7 * (week - 1) + wd)
                got = reached_codes(p, week) if course == "BI-LA1" else None
                cs = ", ".join(f'"{x}"' for x in (got[0] if got else codes(course, label, topic, plan)))
                mark = f'"{got[1]}"' if got else "null"
                out.append(f"            Lecture(\"{label}\", {week}, LocalDate.parse(\"{d}\"), listOf({cs}), reached = {mark}),")
            out.append("        ),")
        out.append("    ),")
        out.append(")")
        out.append("")
    OUT.write_text("\n".join(out))
    print(f"wrote {OUT}")


if __name__ == "__main__":
    plans = sys.argv[1] if len(sys.argv) > 1 else os.environ.get("SCHEDULE_PLANS")
    if not plans:
        sys.exit("Set SCHEDULE_PLANS to the folder with the course plans BI-LA1.yaml and BI-DML.yaml.")
    main(Path(plans))
