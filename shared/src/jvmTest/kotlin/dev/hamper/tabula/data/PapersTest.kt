package dev.hamper.tabula.data

import dev.hamper.tabula.la.*
import dev.hamper.tabula.screens.reviewLink
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertNotNull
import org.junit.Assert.assertTrue
import org.junit.Test

/**
 * Papers split into parts: the parts are the task word for word, their points and rubric lines add up, every part of a
 * split problem has a model solution and something to review. Runs over every past paper of every course and many
 * generated ones, so a DML paper with parts gets the same checks.
 */
class PapersTest {
    // built once per test JVM: JUnit makes a new instance for every test method, and 360 generated papers each time
    // were most of this class's run
    companion object {
        private val la1Generated by lazy { (1..300).map { la1GeneratedPaper(it) } }
        private val all by lazy { Courses.flatMap { it.papers } + la1Generated + Courses.flatMap { c -> (1..30).map { c.generatedPaper(it) } } }
    }

    @Test fun partsAreTheTaskWordForWord() {
        for (paper in all) for (p in paper.problems) {
            assertEquals("${paper.id} ${p.n}: parts joined are the task", p.text, p.units.joinToString(" ") { it.text })
            assertFalse("${paper.id} ${p.n}: a split mark left in the text", p.units.any { '¦' in it.text })
            p.units.forEach { assertTrue("${paper.id} ${p.n}: empty part", it.text.isNotBlank()) }
        }
    }

    @Test fun pointsAddUpPartByPart() {
        for (paper in all) for (p in paper.problems) {
            assertEquals("${paper.id} ${p.n}: parts add up", p.pts, p.units.sumOf { it.pts })
            for (u in p.units) assertEquals("${paper.id} ${p.n} ${u.label}: rubric of the part", u.pts, u.checklist.sumOf { it.pts })
            assertEquals("${paper.id} ${p.n}: the checklist is the parts' lines in order", p.checklist, p.units.flatMap { it.checklist })
        }
    }

    @Test fun labelsAreLettersWhenThereAreSeveralParts() {
        for (paper in all) for (p in paper.problems) {
            if (p.units.size == 1) assertEquals("", p.units[0].label)
            else assertEquals(p.units.indices.map { "${'a' + it})" }, p.units.map { it.label })
        }
    }

    @Test fun la1PartsHaveSolutionsAndSomethingToReview() {
        for (paper in La1.papers + la1Generated) for (p in paper.problems) {
            assertTrue("${paper.id} ${p.n}: split into parts", p.parts.isNotEmpty())
            for (u in p.units) {
                assertTrue("${paper.id} ${p.n} ${u.label}: model solution along its Postup ${u.solution?.problems()}", u.solution?.problems()?.isEmpty() == true)
                assertNotNull("${paper.id} ${p.n} ${u.label}: answer", u.answer)
                val link = reviewLink(u, La1)
                assertNotNull("${paper.id} ${p.n} ${u.label}: what to review", link)
                // a lesson step when the course teaches it in a lesson, the item itself otherwise
                assertTrue("${paper.id} ${p.n} ${u.label}: ${link!!.route}", link.route.substringBefore(':') in setOf("step", "concept", "proof", "theorem", "gen", "lesson"))
            }
        }
    }

    @Test fun la1SplitsAsTheTestsAsk() {
        val byId = La1.papers.associateBy { it.id }
        fun shape(id: String) = byId.getValue(id).problems.map { p -> p.units.map { it.pts } }
        // problem 1 is one sentence, its 7 points are the paper's; the other splits are our estimate
        assertEquals(listOf(listOf(7), listOf(4, 4, 2, 2), listOf(2, 2, 2, 5)), shape("sova-2025"))
        assertEquals(listOf(listOf(7), listOf(4, 5, 3), listOf(2, 2, 2, 5)), shape("slon-2024"))
        assertEquals(listOf(listOf(7), listOf(6, 3, 3), listOf(2, 2, 4, 3)), shape("medved-2024"))
        assertEquals(listOf(listOf(7), listOf(6, 4, 2), listOf(2, 2, 2, 5)), shape("sova-2023"))
        assertEquals(listOf(listOf(7), listOf(4, 4, 4), listOf(2, 2, 4, 3)), shape("slepice-2023"))
        // the official sample test of MARAST: points per problem from the page, the split into parts ours
        assertEquals(listOf(listOf(4, 3), listOf(12), listOf(2, 5, 4)), shape("marast-ukazka-2"))
        // the fit-wiki tests share one shape: problem 1 is the parameter problem with its header
        for (paper in La1.papers.filter { "fit-wiki" in it.src }) {
            // its 7 points are the paper's, unless the photo does not show them (včelka 2023)
            assertEquals("nečitateľné" in paper.src, paper.problems[0].units[0].estimate)
            // the parts' points are ours, except where the transcription has them (veverka 2024, problem 3: 2 + 2 + 3 + 4)
            assertTrue(paper.problems.drop(1).all { p -> p.units.all { it.estimate } || p.note?.contains("body 2 + 2 + 3 + 4 sú z prepisu") == true })
            assertEquals(HeaderP1, paper.problems[0].note)
        }
    }

    @Test fun computedAnswersOfTheSplitPapers() {
        val sova = La1.papers.first { it.id == "sova-2025" }
        // the set of the screenshot is no subspace: the first pair whose sum falls out, as the old answer had it
        assertEquals("Množina podpriestorom nie je: §(1,0,0,0)+(0,0,1,0)=(1,0,1,0)§ v nej nie je.", sova.problems[2].units[2].answer)
        assertEquals("§5^2-1=24§ vektorov: všetky nenulové prvky §\\langle\\mathbf{u},\\mathbf{v}\\rangle§.", sova.problems[1].units[3].answer)
        assertEquals("Napr. §\\mathbf{y}=\\mathbf{u}+\\mathbf{v}=(4,0,0,0)§.", sova.problems[1].units[2].answer)
    }

    @Test fun anOldStyleProblemIsOnePart() {
        val p = PaperProblem(1, 10, "Indukcia", "Dokažte, že ...", 25, listOf(Rubric("Báza", 3), Rubric("Krok", 7)), "Platí.")
        assertEquals(1, p.units.size)
        assertEquals(p.text, p.units[0].text)
        assertEquals(10, p.units[0].pts)
        assertFalse(p.units[0].estimate)
    }

    /**
     * A proof's model solution has each round's assumption, as on paper: the prompt of a round that sets one up
     * ("§(\\Leftarrow)§: nech napr. …") disappears in the solution, so the round says it in [ProofRound.given] (LLM check
     * 17. 11.: sova 2025, 3d started the (⇐) direction with "Potom 1x − βy − γz = θ"). Every proof of both courses.
     */
    @Test fun everyRoundAssumptionIsInTheSolution() {
        val sets = Regex("""(^|[\s:,(])[Nn]ech\s|\\(Rightarrow|Leftarrow|implies|impliedby)\)?[$§]?\s*:""")
        val missing = ProofById.values.flatMap { p -> p.rounds.withIndex().filter { (_, r) -> sets.containsMatchIn(r.prompt) && r.given == null }.map { "${p.id} round ${it.index}: ${it.value.prompt}" } }
        assertTrue("rounds whose prompt sets up an assumption the solution would leave out (give it as given =):\n" + missing.joinToString("\n"), missing.isEmpty())
        for (p in ProofById.values) {
            val says = proofSolution(p).steps.joinToString(" ") { it.say }
            p.rounds.forEach { r -> r.given?.let { assertTrue("${p.id}: ${it}", it.trimEnd() in says) } }
        }
        val d = La1Papers.first { it.id == "sova-2025" }.problems.first { it.n == 3 }.units[3].solution!!
        val back = d.steps.first { "1\\mathbf{x}-\\beta" in it.say }.say
        assertTrue(back, back.indexOf("\\mathbf{x}=\\beta\\mathbf{y}+\\gamma\\mathbf{z}") in 0 until back.indexOf("1\\mathbf{x}-\\beta"))
    }

    /**
     * A part with many right answers (OwnBasis: a completion, a basis of a span): every right basis a student may have
     * is accepted, and the later parts come out in it with the same points and checklists and model solutions along
     * their Postup; a dependent set or a vector outside M is refused, with GEM for the dependent one. Right bases from
     * the one-tap vectors in every order and with a vector multiplied, over every past and generated problem.
     */
    @Test fun ownBasisIsCheckedAndTheLaterPartsFollowIt() {
        var right = 0; var wrong = 0
        for (paper in all) for (p in paper.problems) {
            val o = p.own ?: continue
            val f: dev.hamper.tabula.la.Field = o.input.p?.let { dev.hamper.tabula.la.Field.Zp(it) } ?: dev.hamper.tabula.la.Field.R
            val quick = o.input.quick.map { it.second }
            val k = o.input.count.last
            val whole = o.input.quick.first().first.startsWith("\\mathbf{e}")
            fun subsets(from: List<dev.hamper.tabula.la.Vec>, k: Int): List<List<dev.hamper.tabula.la.Vec>> =
                if (k == 0) listOf(emptyList()) else from.indices.flatMap { i -> subsets(from.drop(i + 1), k - 1).map { listOf(from[i]) + it } }
            for (pick in subsets(quick, k)) for (variant in 0..1) {
                val e = if (variant == 0) pick.reversed() else listOf(f.scale(dev.hamper.tabula.la.Frac.of(2), pick[0])) + pick.drop(1)
                val b = o.basis(e)
                val ok = f.rank(b) == b.size && (if (whole) b.size == b[0].size else b.all { f.inSpan(quick, it) } && b.size == f.rank(quick))
                val r = o.input.check(e.map { listOf(it) })
                assertEquals("${paper.id} ${p.n}: ${e.map { it.tex() }} ${r.head}", ok, r.ok)
                if (!ok) { wrong++; assertNotNull("${paper.id} ${p.n}: GEM for a dependent set", o.gem(b)); continue }
                right++
                val q = p.inBasis(e)
                assertEquals("${paper.id} ${p.n}: points", p.units.map { it.pts to it.checklist }, q.units.map { it.pts to it.checklist })
                for (u in q.units) assertTrue("${paper.id} ${p.n} ${u.label} in ${b.map { it.tex() }}: ${u.solution?.problems()}", u.solution?.problems()?.isEmpty() != false)
            }
            // outside M (a span) or the zero vector (a completion): refused
            val bad = List(k) { i -> if (i == 0) List(quick[0].size) { dev.hamper.tabula.la.Frac.ZERO } else quick[i % quick.size] }
            assertFalse("${paper.id} ${p.n}: zero vector", o.input.check(bad.map { listOf(it) }).ok)
        }
        assertTrue("right $right, wrong $wrong", right > 500 && wrong > 50)
    }
}
