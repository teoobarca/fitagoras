package dev.hamper.tabula.la

import dev.hamper.tabula.compat.BigInteger
import dev.hamper.tabula.compat.*
import dev.hamper.tabula.compat.JMath

/*
 * Z_p^n exactly: vectors, operations modulo p, spans and subspaces. Three different objects are kept apart:
 * a vector (a point), an ordered basis (a tuple of vectors) and a subspace (a set of vectors). Two bases of the same
 * subspace give the same [Subspace]: its identity is the reduced row echelon form of any of its bases, which is unique.
 * Counts are exact (BigInteger), enumeration only for small spaces. Checked against brute force in FiniteSpaceTest.
 */

/** A vector of Z_p^n: components 0..p-1. */
typealias ZVec = List<Int>

class FiniteSpace(val p: Int, val n: Int) {
    init {
        require(p >= 2 && (2..p / 2).none { p % it == 0 }) { "p must be a prime, got $p" }
        require(n in 1..8) { "n in 1..8, got $n" }
    }

    val zero: ZVec = List(n) { 0 }

    /** p^n, the number of vectors (only for spaces small enough to enumerate). */
    val size: Int get() = JMath.toIntExact(bigIntegerOf(p.toLong()).pow(n).toLong())

    fun mod(x: Int) = ((x % p) + p) % p
    fun vec(vararg x: Int): ZVec = vec(x.toList())
    fun vec(x: List<Int>): ZVec { require(x.size == n); return x.map(::mod) }
    fun add(a: ZVec, b: ZVec): ZVec = List(n) { mod(a[it] + b[it]) }
    fun scale(c: Int, a: ZVec): ZVec = List(n) { mod(c * a[it]) }
    fun combo(cs: List<Int>, vs: List<ZVec>): ZVec = cs.indices.fold(zero) { acc, i -> add(acc, scale(cs[i], vs[i])) }
    fun inv(a: Int): Int { val x = mod(a); require(x != 0); return (1 until p).first { mod(it * x) == 1 } }

    /** Every vector, in the order of [index]. */
    fun all(): List<ZVec> = List(size) { vector(it) }
    fun index(v: ZVec): Int = v.foldRight(0) { x, acc -> acc * p + x }
    fun vector(i: Int): ZVec { var r = i; return List(n) { val x = r % p; r /= p; x } }

    /** Reduced row echelon form of the rows, zero rows dropped: the same for every generating set of one span. */
    fun rref(rows: List<ZVec>): List<ZVec> {
        val m = rows.map { vec(it).toMutableList() }.toMutableList()
        var r = 0
        for (col in 0 until n) {
            val piv = (r until m.size).firstOrNull { m[it][col] != 0 } ?: continue
            m.add(r, m.removeAt(piv))
            val k = inv(m[r][col])
            m[r] = m[r].map { mod(it * k) }.toMutableList()
            for (i in m.indices) if (i != r && m[i][col] != 0) {
                val f = m[i][col]
                m[i] = MutableList(n) { j -> mod(m[i][j] - f * m[r][j]) }
            }
            r++
            if (r == m.size) break
        }
        return m.take(r).map { it.toList() }
    }

    fun rank(vs: List<ZVec>) = rref(vs).size
    fun isLN(vs: List<ZVec>) = rank(vs) == vs.size

    /** The subspace generated by [vs] (the span; {θ} for none). */
    fun span(vs: List<ZVec>): Subspace = Subspace(this, rref(vs))

    /** All p^d vectors of a span. */
    fun elements(s: Subspace): Set<ZVec> {
        val b = s.basis
        val out = LinkedHashSet<ZVec>()
        val total = bigIntegerOf(p.toLong()).pow(b.size).toInt()
        for (k in 0 until total) { var r = k; out += combo(List(b.size) { val x = r % p; r /= p; x }, b) }
        return out
    }

    fun contains(s: Subspace, v: ZVec) = rank(s.basis + listOf(v)) == s.dim

    /** Definice 2.7 on a finite set: non-empty, closed under + and under multiplication by every scalar. */
    fun isSubspace(set: Set<ZVec>): Boolean =
        set.isNotEmpty() && set.all { a -> set.all { b -> add(a, b) in set } && (0 until p).all { c -> scale(c, a) in set } }

    /**
     * Every subspace of dimension [d], each exactly once: one per reduced echelon form (pivot columns, then the free
     * entries right of each pivot that are not in a pivot column). Only for small spaces.
     */
    fun subspaces(d: Int): List<Subspace> {
        require(d in 0..n)
        val out = ArrayList<Subspace>()
        for (pivots in combinations(n, d)) {
            val free = pivots.flatMapIndexed { row, pc -> (pc + 1 until n).filter { it !in pivots }.map { row to it } }
            val total = bigIntegerOf(p.toLong()).pow(free.size).toInt()
            for (k in 0 until total) {
                val m = List(d) { row -> MutableList(n) { if (it == pivots[row]) 1 else 0 } }
                var r = k
                for ((row, col) in free) { m[row][col] = r % p; r /= p }
                out += Subspace(this, m.map { it.toList() })
            }
        }
        return out
    }

    fun allSubspaces(): List<Subspace> = (0..n).flatMap { subspaces(it) }

    /* ---- counts, exact ---- */

    private val P = bigIntegerOf(p.toLong())

    /** |P| = p^d for a subspace of dimension d (Poznámka 2.67). */
    fun vectorsIn(d: Int): BigInteger = P.pow(d)

    /** Ordered LN d-tuples of vectors in a space of dimension [m]: (p^m - 1)(p^m - p)...(p^m - p^(d-1)). */
    fun orderedLN(d: Int, m: Int = n): BigInteger = (0 until d).fold(BigIntegerOne) { acc, i -> acc * (P.pow(m) - P.pow(i)) }

    /** Ordered bases of one subspace of dimension d (the empty basis of {θ} counts once). */
    fun basesOf(d: Int): BigInteger = orderedLN(d, d)

    /** d-dimensional subspaces of Z_p^n: ordered LN d-tuples in Z_p^n, each subspace counted once per its basis. */
    fun subspaceCount(d: Int): BigInteger { require(d in 0..n); return orderedLN(d) / basesOf(d) }

    fun allSubspaceCount(): BigInteger = (0..n).fold(BigIntegerZero) { acc, d -> acc + subspaceCount(d) }

    /* ---- how it is written ---- */

    fun tex(v: ZVec): String = if (v == zero) "\\theta" else v.joinToString(",", "(", ")")
    /** The way a corner of the cube or a cell is labelled: "101". */
    fun label(v: ZVec): String = v.joinToString("")
    fun spaceTex(): String = "\\mathbb{Z}_{$p}^{$n}"

    companion object {
        fun combinations(n: Int, k: Int): List<List<Int>> =
            if (k == 0) listOf(emptyList()) else (0 until n).flatMap { first -> combinations(n - first - 1, k - 1).map { rest -> listOf(first) + rest.map { it + first + 1 } } }
    }
}

/**
 * A subspace of Z_p^n by its identity: the reduced row echelon basis. Two different bases of the same subspace give
 * equal Subspaces, so a list of subspaces never holds one subspace twice.
 */
class Subspace internal constructor(val space: FiniteSpace, val basis: List<ZVec>) {
    val dim get() = basis.size
    val elements: Set<ZVec> by lazy { space.elements(this) }
    val size: BigInteger get() = space.vectorsIn(dim)
    fun contains(v: ZVec) = space.contains(this, v)
    /** "{θ,(1,0),(2,0)}" in the order of increasing index, θ first. */
    fun setTex(): String = elements.sortedBy { space.index(it) }.joinToString(",", "\\{", "\\}") { space.tex(it) }
    /** "⟨(1,0,1),(0,1,1)⟩" by the canonical basis, "{θ}" for the zero subspace. */
    fun spanTex(): String = if (basis.isEmpty()) "\\{\\theta\\}" else basis.joinToString(",", "\\langle ", "\\rangle") { space.tex(it) }
    override fun equals(other: Any?) = other is Subspace && other.space.p == space.p && other.space.n == space.n && other.basis == basis
    override fun hashCode() = basis.hashCode() * 31 + space.p
    override fun toString() = "Subspace(p=${space.p}, n=${space.n}, $basis)"
}
